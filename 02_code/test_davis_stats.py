import pandas as pd

df = pd.read_csv('03_experiments/audits/dti_davis_acquisition_20261006_v2/davis.csv')
print('Shape:', df.shape)
print('Unique ID1 (drugs):', df['ID1'].nunique())
print('Unique X1 (SMILES):', df['X1'].nunique())
print('Unique ID2 (targets):', df['ID2'].nunique())
print('Unique X2 (sequences):', df['X2'].nunique())
print('Y min, max, median:', df['Y'].min(), df['Y'].max(), df['Y'].median())
censored = (df['Y'] == 10000).sum()
active = (df['Y'] < 10000).sum()
potent = (df['Y'] <= 100).sum()
total = len(df)
print(f'Censored (Y == 10000): {censored} ({censored / total * 100:.2f}%)')
print(f'Active (Y < 10000): {active} ({active / total * 100:.2f}%)')
print(f'Potent (Y <= 100 nM): {potent} ({potent / total * 100:.2f}%)')
n_d = df['ID1'].nunique()
n_t = df['ID2'].nunique()
print(f'Matrix completeness: {n_d} * {n_t} = {n_d * n_t} vs {total} rows')
